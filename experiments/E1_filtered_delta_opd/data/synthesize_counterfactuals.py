DEFAULT_TOPIC_WEIGHTS: dict[str, float] = {
    "patterned_grid": 1.0,
    "flag": 1.0,
    "game_board": 1.0,
    "chess_position": 1.0,
    "animal": 1.0,
}


# ---------------------------------------------------------------------------
# Sample dataclass — same shape as ViRL39KSample / POPEStyleSample.
# ---------------------------------------------------------------------------

@dataclass
class SyntheticSample:
    sample_id: str
    question: str
    image_paths: list[Path]
    gold: str
    extras: dict[str, Any] = field(default_factory=dict)

    def load_images(self) -> list[Image.Image]:
        return [Image.open(p).convert("RGB") for p in self.image_paths]


# ---------------------------------------------------------------------------
# Shared drawing helpers.
# ---------------------------------------------------------------------------

_FONT_CANDIDATES = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/Library/Fonts/Arial Bold.ttf",
    "/Library/Fonts/Arial.ttf",
    "/System/Library/Fonts/Helvetica.ttc",
    "/System/Library/Fonts/Supplemental/Arial.ttf",
]


def _load_font(size: int) -> ImageFont.ImageFont:
    """Best-effort TTF load with system fallbacks → PIL default font."""
    for p in _FONT_CANDIDATES:
        if os.path.exists(p):
            try:
                return ImageFont.truetype(p, size)
            except OSError:
                continue
    try:
        return ImageFont.truetype("DejaVuSans-Bold.ttf", size)
    except OSError:
        return ImageFont.load_default()


def _draw_centered_text(
    draw: ImageDraw.ImageDraw,
    text: str,
    cx: float,
    cy: float,
    font: ImageFont.ImageFont,
    fill: tuple | str,
) -> None:
    bbox = draw.textbbox((0, 0), text, font=font)
    w = bbox[2] - bbox[0]
    h = bbox[3] - bbox[1]
    # textbbox can have a non-zero offset; subtract it for true centering.
    draw.text(
        (cx - w / 2 - bbox[0], cy - h / 2 - bbox[1]),
        text, font=font, fill=fill,
    )


def _draw_shape(
    draw: ImageDraw.ImageDraw,
    shape: str,
    cx: float,
    cy: float,
    r: float,
    color: tuple | str,
) -> None:
    """Draw a primitive shape (circle, square, triangle, star, diamond) centered at (cx, cy)."""
    if shape == "circle":
        draw.ellipse([cx - r, cy - r, cx + r, cy + r], fill=color)
        return
    if shape == "square":
        draw.rectangle([cx - r, cy - r, cx + r, cy + r], fill=color)
        return
    if shape == "triangle":
        draw.polygon(
            [(cx, cy - r), (cx - r, cy + r * 0.8), (cx + r, cy + r * 0.8)],
            fill=color,
        )
        return
    if shape == "diamond":
        draw.polygon(
            [(cx, cy - r), (cx + r, cy), (cx, cy + r), (cx - r, cy)],
            fill=color,
        )
        return
    if shape == "star":
        pts: list[tuple[float, float]] = []
        for i in range(10):
            angle = -math.pi / 2 + i * math.pi / 5
            rad = r if i % 2 == 0 else r / 2.4
            pts.append((cx + rad * math.cos(angle), cy + rad * math.sin(angle)))
        draw.polygon(pts, fill=color)
        return
    raise ValueError(f"unknown shape: {shape!r}")


# ---------------------------------------------------------------------------
# Topic 1: patterned grid.
# ---------------------------------------------------------------------------

_GRID_SHAPES = ["circle", "square", "triangle", "star", "diamond"]
_GRID_PALETTE = [
    "#3366cc", "#cc3366", "#33cc66", "#cc6633",
    "#6633cc", "#cccc33", "#33cccc", "#cc33cc",
]


def gen_patterned_grid(rng: random.Random, idx: int) -> tuple[Image.Image, str, str, dict]:
    rows = rng.randint(3, 10)
    cols = rng.randint(3, 10)
    shape_type = rng.choice(_GRID_SHAPES)
    color = rng.choice(_GRID_PALETTE)
    bg = rng.choice(["white", "#f7f7f0", "#fafafa"])

    canvas_w, canvas_h = 512, 512
    img = Image.new("RGB", (canvas_w, canvas_h), bg)
    draw = ImageDraw.Draw(img)

    margin = 40
    avail_w = canvas_w - 2 * margin
    avail_h = canvas_h - 2 * margin
    cell_w = avail_w / cols
    cell_h = avail_h / rows
    radius = min(cell_w, cell_h) * 0.32

    for r in range(rows):
        for c in range(cols):
            cx = margin + (c + 0.5) * cell_w
            cy = margin + (r + 0.5) * cell_h
            _draw_shape(draw, shape_type, cx, cy, radius, color)

    q_variant = rng.choice(["rows", "cols", "total"])
    if q_variant == "rows":
        question = "How many rows are in the grid?"
        gold = str(rows)
    elif q_variant == "cols":
        question = "How many columns are in the grid?"
        gold = str(cols)
    else:
        plural = f"{shape_type}s"
        question = f"How many {plural} are in the grid?"
        gold = str(rows * cols)

    extras = {
        "topic": "patterned_grid",
        "q_variant": q_variant,
        "rows": rows,
        "cols": cols,
        "shape_type": shape_type,
        "color": color,
    }
    return img, question, gold, extras


# ---------------------------------------------------------------------------
# Topic 2: flag.
# ---------------------------------------------------------------------------

_FLAG_PALETTES = [
    ("#cc0000", "#ffffff"),  # red/white
    ("#0033a0", "#ffffff"),  # blue/white
    ("#00754a", "#ffd200"),  # green/yellow
    ("#cc0000", "#ffd200"),  # red/yellow
    ("#0033a0", "#ffd200"),  # blue/yellow
    ("#000000", "#cc0000"),  # black/red
    ("#cc0000", "#000000"),
]


def gen_flag(rng: random.Random, idx: int) -> tuple[Image.Image, str, str, dict]:
    orientation = rng.choice(["horizontal", "vertical"])
    n_stripes = rng.randint(3, 13)
    colors = rng.choice(_FLAG_PALETTES)
    has_canton = rng.random() < 0.5
    # Star count drawn even if has_canton=False so the manifest is uniform.
    n_stars = rng.randint(1, 25) if has_canton else 0

    canvas_w, canvas_h = 640, 400
    img = Image.new("RGB", (canvas_w, canvas_h), colors[1])
    draw = ImageDraw.Draw(img)

    if orientation == "horizontal":
        stripe_h = canvas_h / n_stripes
        for i in range(n_stripes):
            c = colors[i % 2]
            draw.rectangle([0, i * stripe_h, canvas_w, (i + 1) * stripe_h], fill=c)
    else:
        stripe_w = canvas_w / n_stripes
        for i in range(n_stripes):
            c = colors[i % 2]
            draw.rectangle([i * stripe_w, 0, (i + 1) * stripe_w, canvas_h], fill=c)

    if has_canton:
        cw = canvas_w // 2 if orientation == "horizontal" else canvas_w // 3
        ch = canvas_h // 2 if orientation == "horizontal" else canvas_h // 3
        # Canton is conventionally top-left.
        canton_color = "#0033a0" if colors[0] != "#0033a0" else "#000000"
        star_color = "#ffffff" if canton_color != "#ffffff" else "#ffd200"
        draw.rectangle([0, 0, cw, ch], fill=canton_color)

        # Pack n_stars into a grid; cell size from sqrt(n_stars).
        cols = max(1, int(math.ceil(math.sqrt(n_stars))))
        rows = max(1, int(math.ceil(n_stars / cols)))
        cell_w = cw / cols
        cell_h = ch / rows
        star_r = min(cell_w, cell_h) * 0.32
        placed = 0
        for r in range(rows):
            for c in range(cols):
                if placed >= n_stars:
                    break
                cx = (c + 0.5) * cell_w
                cy = (r + 0.5) * cell_h
                _draw_shape(draw, "star", cx, cy, star_r, star_color)
                placed += 1

    # Pick a question variant that's well-defined for this image.
    if has_canton and rng.random() < 0.6:
        q_variant = "stars"
        question = "How many stars are on the flag?"
        gold = str(n_stars)
    else:
        q_variant = "stripes"
        question = "How many stripes does this flag have?"
        gold = str(n_stripes)

    extras = {
        "topic": "flag",
        "q_variant": q_variant,
        "orientation": orientation,
        "n_stripes": n_stripes,
        "has_canton": has_canton,
        "n_stars": n_stars,
        "colors": list(colors),
    }
    return img, question, gold, extras


# ---------------------------------------------------------------------------
# Topic 3: game board (NxN checker pattern).
# ---------------------------------------------------------------------------

_BOARD_DARK = ["#8b4513", "#2f4f4f", "#000000", "#5a3825"]
_BOARD_LIGHT = ["#f5deb3", "#ede8d0", "#ffffff", "#e0c48f"]


def gen_game_board(rng: random.Random, idx: int) -> tuple[Image.Image, str, str, dict]:
    # Sizes from tic-tac-toe (3) through extended boards (12). Sometimes
    # canonical (3 = tic-tac-toe, 8 = chess/checkers, 10 = Go-style minor).
    n_size = rng.randint(3, 12)
    dark = rng.choice(_BOARD_DARK)
    light = rng.choice(_BOARD_LIGHT)

    canvas = 512
    img = Image.new("RGB", (canvas, canvas), "white")
    draw = ImageDraw.Draw(img)
    margin = 30
    cell = (canvas - 2 * margin) / n_size

    dark_count = 0
    for r in range(n_size):
        for c in range(n_size):
            x0 = margin + c * cell
            y0 = margin + r * cell
            is_dark = (r + c) % 2 == 0
            if is_dark:
                dark_count += 1
            color = dark if is_dark else light
            draw.rectangle([x0, y0, x0 + cell, y0 + cell], fill=color, outline="black", width=1)

    q_variant = rng.choice(["rows", "cols", "dark"])
    if q_variant == "rows":
        question = "How many rows does this game board have?"
        gold = str(n_size)
    elif q_variant == "cols":
        question = "How many columns does this game board have?"
        gold = str(n_size)
    else:
        question = "How many dark colored squares are on the board?"
        gold = str(dark_count)

    extras = {
        "topic": "game_board",
        "q_variant": q_variant,
        "n_size": n_size,
        "dark_count": dark_count,
        "dark_color": dark,
        "light_color": light,
    }
    return img, question, gold, extras


# ---------------------------------------------------------------------------
# Topic 4: chess position (variable piece counts on 8x8).
# ---------------------------------------------------------------------------

_CHESS_PIECE_LETTERS = ["P", "N", "B", "R", "Q"]
_CHESS_PIECE_WEIGHTS = [0.50, 0.15, 0.15, 0.15, 0.05]


def _alloc_chess_pieces(n: int, rng: random.Random) -> list[str]:
    """Allocate ``n`` pieces: always 1 king (if n>0), the rest weighted by typical frequency."""
    if n <= 0:
        return []
    pieces = ["K"]
    for _ in range(n - 1):
        pieces.append(rng.choices(_CHESS_PIECE_LETTERS, weights=_CHESS_PIECE_WEIGHTS, k=1)[0])
    rng.shuffle(pieces)
    return pieces


def gen_chess_position(rng: random.Random, idx: int) -> tuple[Image.Image, str, str, dict]:
    n_size = 8
    target_white = rng.randint(2, 16)
    target_black = rng.randint(2, 16)

    all_squares = [(r, c) for r in range(n_size) for c in range(n_size)]
    rng.shuffle(all_squares)
    capacity = len(all_squares)
    total_target = min(target_white + target_black, capacity)
    # Renormalize if both targets together exceed 64 (very rare since max 32).
    if target_white + target_black > total_target:
        scale = total_target / (target_white + target_black)
        n_white = int(round(target_white * scale))
        n_black = total_target - n_white
    else:
        n_white = target_white
        n_black = target_black

    chosen = all_squares[: n_white + n_black]
    white_squares = chosen[:n_white]
    black_squares = chosen[n_white: n_white + n_black]
    white_pieces = _alloc_chess_pieces(n_white, rng)
    black_pieces = _alloc_chess_pieces(n_black, rng)

    canvas = 512
    img = Image.new("RGB", (canvas, canvas), "white")
    draw = ImageDraw.Draw(img)
    margin = 30
    cell = (canvas - 2 * margin) / n_size

    # Board
    for r in range(n_size):
        for c in range(n_size):
            x0 = margin + c * cell
            y0 = margin + r * cell
            color = "#8b4513" if (r + c) % 2 == 0 else "#f5deb3"
            draw.rectangle([x0, y0, x0 + cell, y0 + cell], fill=color)

    # Pieces as colored discs with a letter label
    disc_r = cell * 0.36
    font = _load_font(int(cell * 0.42))

    def _draw_piece(sq, piece_letter, side):
        r, c = sq
        cx = margin + (c + 0.5) * cell
        cy = margin + (r + 0.5) * cell
        disc_fill = "#ffffff" if side == "white" else "#1a1a1a"
        label_fill = "#000000" if side == "white" else "#ffffff"
        outline = "#1a1a1a"
        draw.ellipse(
            [cx - disc_r, cy - disc_r, cx + disc_r, cy + disc_r],
            fill=disc_fill, outline=outline, width=2,
        )
        _draw_centered_text(draw, piece_letter, cx, cy, font, label_fill)

    for sq, p in zip(white_squares, white_pieces):
        _draw_piece(sq, p, "white")
    for sq, p in zip(black_squares, black_pieces):
        _draw_piece(sq, p, "black")

    # Question
    n_white_pawns = sum(1 for p in white_pieces if p == "P")
    n_black_pawns = sum(1 for p in black_pieces if p == "P")
    variants = [
        ("total_white", "How many white pieces are on the board?", n_white),
        ("total_black", "How many black pieces are on the board?", n_black),
    ]
    if n_white_pawns > 0 or rng.random() < 0.5:
        variants.append(("pawns_white", "How many white pawns are on the board?", n_white_pawns))
    if n_black_pawns > 0 or rng.random() < 0.5:
        variants.append(("pawns_black", "How many black pawns are on the board?", n_black_pawns))

    q_variant, question, gold_int = rng.choice(variants)
    gold = str(gold_int)

    extras = {
        "topic": "chess_position",
        "q_variant": q_variant,
        "n_white": n_white,
        "n_black": n_black,
        "n_white_pawns": n_white_pawns,
        "n_black_pawns": n_black_pawns,
    }
    return img, question, gold, extras


# ---------------------------------------------------------------------------
# Topic 5: animal silhouette with variable leg count.
# ---------------------------------------------------------------------------

# Canonical leg counts for "natural" examples; counterfactuals deviate.
_ANIMAL_CANONICAL: dict[str, int] = {
    "quadruped": 4,
    "biped": 2,
    "hexapod": 6,
    "octopod": 8,
}


def gen_animal_silhouette(rng: random.Random, idx: int) -> tuple[Image.Image, str, str, dict]:
    body_type = rng.choice(list(_ANIMAL_CANONICAL.keys()))
    canonical_legs = _ANIMAL_CANONICAL[body_type]

    # 30% canonical / 70% counterfactual sampled uniformly over 0..10.
    if rng.random() < 0.3:
        n_legs = canonical_legs
        is_counterfactual = False
    else:
        # Avoid landing back on canonical when we want a counterfactual.
        candidates = [k for k in range(0, 11) if k != canonical_legs]
        n_legs = rng.choice(candidates)
        is_counterfactual = True

    canvas_w, canvas_h = 512, 384
    bg = rng.choice(["white", "#f4f4ee", "#eef4ee"])
    img = Image.new("RGB", (canvas_w, canvas_h), bg)
    draw = ImageDraw.Draw(img)

    body_fill = "black" if rng.random() < 0.8 else rng.choice(["#1a1a1a", "#3a2a2a", "#2a3a2a"])

    body_w = rng.randint(220, 320)
    body_h = rng.randint(80, 120)
    body_cx = canvas_w // 2 - 20
    body_cy = canvas_h // 2 + 10
    body_left = body_cx - body_w // 2
    body_right = body_cx + body_w // 2
    body_top = body_cy - body_h // 2
    body_bot = body_cy + body_h // 2
    draw.ellipse([body_left, body_top, body_right, body_bot], fill=body_fill)

    # Head: smaller ellipse, top-right
    head_r = rng.randint(40, 55)
    head_cx = body_right + 5
    head_cy = body_cy - body_h // 2 - 5
    draw.ellipse([head_cx - head_r, head_cy - head_r, head_cx + head_r, head_cy + head_r], fill=body_fill)

    # Optional tail (left side)
    if body_type != "biped" and rng.random() < 0.6:
        tail_len = rng.randint(40, 70)
        draw.polygon(
            [(body_left + 5, body_cy - 10),
             (body_left - tail_len, body_cy - 25),
             (body_left + 5, body_cy + 10)],
            fill=body_fill,
        )

    # Legs: evenly spaced along the bottom of the body, inset from edges.
    leg_w = rng.randint(10, 16)
    leg_h = rng.randint(70, 110)
    if n_legs > 0:
        leg_inset = 30
        usable_w = (body_right - leg_inset) - (body_left + leg_inset)
        if n_legs == 1:
            xs = [body_cx]
        else:
            xs = [body_left + leg_inset + i * usable_w / (n_legs - 1) for i in range(n_legs)]
        for x in xs:
            draw.rectangle(
                [x - leg_w / 2, body_bot - 8, x + leg_w / 2, body_bot + leg_h],
                fill=body_fill,
            )

    question = "How many legs does the creature in the image have?"
    gold = str(n_legs)

    extras = {
        "topic": "animal",
        "q_variant": "legs",
        "body_type": body_type,
        "canonical_legs": canonical_legs,
        "n_legs": n_legs,
        "is_counterfactual": is_counterfactual,
    }
    return img, question, gold, extras


# ---------------------------------------------------------------------------
# Build driver.
# ---------------------------------------------------------------------------

TOPIC_GENERATORS: dict[str, Callable[[random.Random, int], tuple[Image.Image, str, str, dict]]] = {
    "patterned_grid": gen_patterned_grid,
    "flag": gen_flag,
    "game_board": gen_game_board,
    "chess_position": gen_chess_position,
    "animal": gen_animal_silhouette,
}


def _topic_seed(main_seed: int, topic: str) -> int:
    """Stable per-topic seed offset (uses Python's hash but masked so it's reproducible
    within a single Python process; for cross-process determinism we further seed by idx)."""
    # SHA-style stable hash so re-runs match across Python invocations.
    import hashlib
    h = hashlib.sha256(f"{main_seed}:{topic}".encode()).digest()
    return int.from_bytes(h[:4], "big")


def _allocate_per_topic_counts(
    n_samples: int, weights: dict[str, float],
) -> dict[str, int]:
    topics = list(weights.keys())
    total_w = sum(weights.values())
    counts: dict[str, int] = {}
    assigned = 0
    for i, t in enumerate(topics):
        if i == len(topics) - 1:
            counts[t] = n_samples - assigned
        else:
            n = int(round(n_samples * weights[t] / total_w))
            counts[t] = n
            assigned += n
    return counts


def build_synthetic_counterfactuals(
    out_dir: Path | str,
    *,
    n_samples: int = 1500,
    topic_weights: Optional[dict[str, float]] = None,
    seed: int = 42,
) -> Path:
    """Synthesize ``n_samples`` images + write a manifest.jsonl into ``out_dir``.

    Returns the manifest path. Per-topic counts are derived from
    ``topic_weights`` (default uniform across all 5 topics).
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    weights = dict(topic_weights or DEFAULT_TOPIC_WEIGHTS)
    counts = _allocate_per_topic_counts(n_samples, weights)
    logger.info("[synth] target counts: %s (seed=%d)", counts, seed)

    manifest_path = out_dir / "manifest.jsonl"
    n_written = 0
    with open(manifest_path, "w") as mf:
        for topic, count in counts.items():
            topic_dir = out_dir / topic
            topic_dir.mkdir(exist_ok=True)
            base_seed = _topic_seed(seed, topic)
            for idx in range(count):
                rng = random.Random(base_seed + idx)
                img, question, gold, extras = TOPIC_GENERATORS[topic](rng, idx)

                filename = f"{topic}_{idx:05d}.png"
                image_path = topic_dir / filename
                img.save(image_path)

                entry = {
                    "sample_id": f"synth_{topic}_{idx:05d}",
                    "topic": topic,
                    "image_path": str(image_path.relative_to(out_dir)),
                    "question": question,
                    "gold": gold,
                    "extras": extras,
                }
                mf.write(json.dumps(entry, ensure_ascii=False) + "\n")
                n_written += 1
            logger.info("[synth] topic=%s wrote %d → %s/", topic, count, topic_dir.name)

    logger.info("[synth] manifest: %s (%d total)", manifest_path, n_written)
    return manifest_path


def iter_synthetic_counterfactuals(
    out_dir: Path | str,
) -> Iterator[SyntheticSample]:
    """Stream samples from ``out_dir/manifest.jsonl`` (build first)."""
    out_dir = Path(out_dir)
    manifest_path = out_dir / "manifest.jsonl"
    if not manifest_path.exists():
        raise FileNotFoundError(
            f"No manifest at {manifest_path}. Run "
            f"`python -m experiments.E1_filtered_delta_opd.data.synthesize_counterfactuals --out-dir {out_dir}` first."
        )

    n = 0
    with open(manifest_path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            entry = json.loads(line)
            image_path = out_dir / entry["image_path"]
            extras = dict(entry["extras"])
            extras.setdefault("topic", entry["topic"])
            extras.setdefault("source", "synth_counterfactual_v1")
            yield SyntheticSample(
                sample_id=entry["sample_id"],
                question=entry["question"],
                image_paths=[image_path],
                gold=entry["gold"],
                extras=extras,
            )
            n += 1
    logger.info("[synth] yielded %d samples from %s", n, manifest_path)


