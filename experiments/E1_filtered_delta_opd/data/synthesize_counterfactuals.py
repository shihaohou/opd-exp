"""
Parametric synthesis of VLMBias-like adversarial recognition counterfactuals.

Why this exists:
    VLMBias `withtitle` / `remove_background_*` siblings share base images
    with the `main` eval set, so they're off-limits for training. We need
    fresh assets that exercise the same failure mode: image triggers a
    recognition prior; canonical-prior answer is wrong; correct answer
    requires visual counting / inspection. This module synthesizes those
    images from parametric templates — every pixel is generated by us, so
    there is no possibility of leakage with VLMBias `main`.

Five topics, each picked to mirror a VLMBias failure mode:
    * ``patterned_grid``  — variable-size NxM grids of shapes.
                            Question: rows / cols / total shape count.
                            (Mirrors VLMBias "Patterned Grid" topic.)
    * ``flag``            — horizontal/vertical striped flags ± a canton
                            with N stars.
                            Question: # stripes or # stars.
                            (Mirrors VLMBias "Flags" — US prior = 13 stripes
                            + 50 stars; ours vary freely.)
    * ``game_board``      — NxN checkerboard, alternating colours.
                            Question: rows / cols / # dark squares.
                            (Mirrors VLMBias "Game Boards" — chess prior = 8.)
    * ``chess_position``  — 8x8 board with N_white + N_black pieces.
                            Question: total / pawns / specific colour.
                            (Mirrors VLMBias "Chess Pieces" — starting
                            position prior = 16+16.)
    * ``animal``          — silhouette critter with variable leg count.
                            Question: # legs.
                            (Approximates VLMBias "Animals" — pure PIL
                            silhouettes won't fire the strong photo-realist
                            recognition prior, but force visual counting on
                            shapes that look animal-adjacent. Documented
                            caveat — see § Limitations below.)

Spec (from ``experiments/E1_filtered_delta_opd/README.md`` § Bucket 3):
    * Target n      : ~1500 (rest of bucket 3 is TallyQA complex)
    * Asset origin  : NEW (never pulled from VLMBias)
    * Answer format : integer → ``\\boxed{N}`` (handled by parquet builder)
    * Determinism   : seed-controlled per (topic, sample_idx)

Two-stage pipeline:
    1. ``build_synthetic_counterfactuals(out_dir, ...)`` renders the
       images to disk + writes ``manifest.jsonl``. Invoked once via CLI.
    2. ``iter_synthetic_counterfactuals(out_dir)`` streams samples from
       the manifest for downstream consumers (precompute, parquet).

The split keeps downstream callers oblivious to synthesis; they see a
loader that points at on-disk PNGs, matching the ViRL39K / POPE-style
shape exactly.

Limitations (documented honestly):
    * Animal silhouettes are deliberately abstract (geometric shapes). They
      give the student counting practice on legs but they will NOT trigger
      a strong "dog" recognition prior the way a photo would. If E1 v1
      fails to move TEI on the Animals topic, this is one of the suspects
      and we may need a CLIP-guided generation pipeline in v2.
    * Chess piece glyphs are letter labels on circles (K/Q/R/B/N/P), not
      Unicode chess characters. Avoids font portability issues; the model
      still sees an 8x8 board with discrete pieces.
"""

